/**
 * Compiles the DTCG tokens in tokens/*.tokens.json into a Tailwind 4 `@theme` block at
 * src/shared/ui/tokens.css.
 *
 * The block starts with `--*: initial`, which removes Tailwind's default theme. Classes that
 * are not backed by a token (`p-5`, `bg-red-500`, `rounded-xl`) then do not exist at all.
 *
 *   pnpm tokens          write tokens.css
 *   pnpm tokens --check  exit 1 if tokens.css is out of date
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import StyleDictionary from 'style-dictionary';
import type { Config, FormatFn } from 'style-dictionary/types';

const tokensDir = fileURLToPath(new URL('.', import.meta.url));
export const OUTPUT = fileURLToPath(new URL('../src/shared/ui/tokens.css', import.meta.url));

const tailwindTheme: FormatFn = ({ dictionary }) => {
  const lines = dictionary.allTokens.map((token) => `  --${token.name}: ${String(token.$value)};`);
  return [
    '/* Generated by tokens/build.ts from tokens/*.tokens.json. Do not edit; run `pnpm tokens`. */',
    '@theme {',
    '  --*: initial;',
    ...lines,
    '}',
    '',
  ].join('\n');
};

const config: Config = {
  source: [`${tokensDir}*.tokens.json`],
  log: { verbosity: 'silent', warnings: 'error' },
  hooks: { formats: { 'tailwind/theme': tailwindTheme } },
  platforms: {
    tailwind: {
      transforms: ['name/kebab', 'color/css', 'fontFamily/css', 'shadow/css/shorthand'],
      files: [{ destination: 'tokens.css', format: 'tailwind/theme' }],
    },
  },
};

/** Renders tokens.css in memory. */
export async function renderThemeCss(): Promise<string> {
  const dictionary = new StyleDictionary(config);
  const [file] = await dictionary.formatPlatform('tailwind');
  if (typeof file?.output !== 'string') throw new Error('style-dictionary produced no output');
  return file.output;
}

async function main(check: boolean): Promise<void> {
  const css = await renderThemeCss();
  if (!check) {
    await writeFile(OUTPUT, css);
    return;
  }
  const current = await readFile(OUTPUT, 'utf8').catch(() => '');
  if (current !== css) {
    process.stderr.write('src/shared/ui/tokens.css is out of date. Run `pnpm tokens`.\n');
    process.exitCode = 1;
  }
}

if (import.meta.main) await main(process.argv.includes('--check'));
